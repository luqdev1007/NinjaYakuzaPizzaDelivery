namespace Assets._Project.Develop.Runtime.Gameplay.Features.Entities.Combat.Explosion
{
    /// <summary>
    /// Как именно призрак сдетонировал. Разделение существует потому, что урон
    /// положен только доведённому до конца взведению.
    /// </summary>
    public enum DetonationKind
    {
        /// <summary>
        /// Взведение доведено до конца, таймер истёк. Полноценный взрыв:
        /// урон + отброс.
        /// </summary>
        Natural = 0,

        /// <summary>
        /// Призрака убили до конца взведения. Урона нет вообще — ни игроку, ни
        /// врагам, ни пропам; остаётся только импульс, приглушённый
        /// ForcedExplosionKnockbackMultiplier.
        ///
        /// Это награда за своевременное убийство, а не наказание: игрок,
        /// успевший добить камикадзе, получает бесплатный буст движения вместо
        /// урона в лицо.
        /// </summary>
        Forced = 1
    }
}
